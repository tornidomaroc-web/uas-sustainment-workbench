"""Export the stored fleet, its flights and findings as a static site (JSON + one page).

The JSON is built by the same view functions the API uses, so the published page shows
exactly what the service would answer. The page is a template in this package; the data
is generated by CI from the code.
"""

from __future__ import annotations

import json
import os
from datetime import UTC, datetime
from importlib import resources
from pathlib import Path

from uas_workbench.assistant.recording import NOTICE as ASSISTANT_NOTICE
from uas_workbench.assistant.recording import load_recordings
from uas_workbench.assistant.recording import to_json as recording_to_json
from uas_workbench.fleet import FleetConfig, load_config

from .app import (
    aircraft_view,
    due_view,
    entries_about,
    entry_view,
    fleet_due,
    flight_view,
    reconcile_view,
)
from .store import Store

NOTICE = (
    "Demonstration fleet. Aircraft and flights marked synthetic are generated from a seed and "
    "describe no real aircraft; their maintenance entries are generated too, and their board "
    "states are computed from them. The two real aircraft are excerpts of public, licensed "
    "logs with positions and device ids removed. Maintenance entries are recorded through the "
    "API and command line of a locally running service, not on this page. Civil fleet "
    "sustainment only."
)


SAMPLE_EVIDENCE_KEY = "SYN-04"  # a synthetic aircraft with an overdue part and a moved one


def export_static(store: Store, out_dir: Path, config: FleetConfig | None = None) -> Path:
    cfg = config or load_config()
    out_dir.mkdir(parents=True, exist_ok=True)
    now = datetime.now(UTC).replace(microsecond=0)
    stamp = now.strftime("%Y-%m-%dT%H:%M:%SZ")  # the form the API models serialise to
    aircraft: list[dict[str, object]] = []
    findings: list[dict[str, object]] = []
    for a in store.aircraft():
        _, result = reconcile_view(store, a, cfg)
        aircraft.append(
            {
                **aircraft_view(store, a, cfg).model_dump(mode="json"),
                # "flights" stays the count from the aircraft view; the records go under "records".
                "records": [flight_view(r).model_dump(mode="json") for r in store.flights(a.key)],
                "reconcile": result.model_dump(mode="json"),
                "due": due_view(store, a, cfg, now)[2].model_dump(mode="json"),
                "entries": [
                    entry_view(store, e).model_dump(mode="json")
                    for e in entries_about(store, a.key)
                ],
            }
        )
        findings.extend(f.model_dump(mode="json") for f in result.findings)
    data = {
        "notice": NOTICE,
        "generated_utc": stamp,
        "as_of": stamp,
        "seed": cfg.seed,
        "tolerance_s": cfg.tolerance_s,
        "due_soon_fraction": cfg.life.due_soon_fraction,
        "aircraft": aircraft,
        "findings": findings,
        "due": [i.model_dump(mode="json") for i in fleet_due(store, cfg, now)],
    }
    # One sample draft evidence pack, for one synthetic aircraft only.
    from uas_workbench.evidence import build_pack, render_html

    sample_key = SAMPLE_EVIDENCE_KEY
    sample = build_pack(
        store,
        sample_key,
        cfg,
        as_of=now,
        commit=os.environ.get("UASW_COMMIT") or None,
        generated_utc=now,
    )
    (out_dir / "evidence").mkdir(exist_ok=True)
    (out_dir / "evidence" / f"{sample_key}.html").write_text(render_html(sample), encoding="utf-8")
    (out_dir / "evidence" / f"{sample_key}.json").write_text(
        json.dumps(sample, indent=1, ensure_ascii=False), encoding="utf-8"
    )
    data["sample_evidence"] = {
        "aircraft_key": sample_key,
        "html": f"evidence/{sample_key}.html",
        "json": f"evidence/{sample_key}.json",
    }
    (out_dir / "fleet.json").write_text(json.dumps(data, indent=1), encoding="utf-8")
    runs = {
        "notice": ASSISTANT_NOTICE,
        "runs": [recording_to_json(r) for r in load_recordings()],
    }
    (out_dir / "assistant.json").write_text(
        json.dumps(runs, indent=1, ensure_ascii=False), encoding="utf-8"
    )
    page = resources.files("uas_workbench.service").joinpath("site/index.html")
    (out_dir / "index.html").write_text(page.read_text("utf-8"), encoding="utf-8")
    return out_dir
